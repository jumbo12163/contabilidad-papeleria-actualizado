
CREATE TABLE TIPO_CUENTA (
    ID_TIPO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(200)
);

CREATE TABLE CUENTA_CONTABLE (
    ID_CUENTA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_TIPO NUMBER NOT NULL,
    CONSTRAINT FK_CUENTA_TIPO
        FOREIGN KEY (ID_TIPO)
        REFERENCES TIPO_CUENTA(ID_TIPO)
);


CREATE TABLE COMPROBANTE_CONTABLE (
    ID_COMPROBANTE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    OBSERVACIONES VARCHAR2(250),
    ESTADO VARCHAR2(15) DEFAULT 'BORRADOR' NOT NULL,
    CONSTRAINT CK_ESTADO_COMPROBANTE
        CHECK (ESTADO IN ('BORRADOR', 'CONTABILIZADO'))
);


CREATE TABLE DETALLE_CONTABLE (
    ID_DETALLE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_COMPROBANTE NUMBER NOT NULL,
    ID_CUENTA NUMBER NOT NULL,
    DEBE NUMBER(12,2) DEFAULT 0 NOT NULL,
    HABER NUMBER(12,2) DEFAULT 0 NOT NULL,

    CONSTRAINT FK_DETALLE_COMPROBANTE
        FOREIGN KEY (ID_COMPROBANTE)
        REFERENCES COMPROBANTE_CONTABLE(ID_COMPROBANTE),

    CONSTRAINT FK_DETALLE_CUENTA
        FOREIGN KEY (ID_CUENTA)
        REFERENCES CUENTA_CONTABLE(ID_CUENTA),

    CONSTRAINT CK_DEBE_NO_NEGATIVO
        CHECK (DEBE >= 0),

    CONSTRAINT CK_HABER_NO_NEGATIVO
        CHECK (HABER >= 0),

    CONSTRAINT CK_DEBE_HABER
        CHECK (
            (DEBE > 0 AND HABER = 0)
            OR
            (HABER > 0 AND DEBE = 0)
        )
);


